-- 1단계: 단순 CRUD. 엔티티는 서로 객체로 참조하지 않고 id(Long)로만 가리키지만, DB 에는 FK 를 건다.

create table users (
    id         bigint generated by default as identity primary key,
    user_id    varchar(50)  not null,
    password   varchar(255) not null,
    created_at timestamptz  not null,
    updated_at timestamptz  not null,
    constraint uk_users_user_id unique (user_id)
);

create table coupon_policy (
    id                  bigint generated by default as identity primary key,
    name                varchar(100) not null,
    discount_value      integer      not null,
    max_discount_amount integer      not null,
    valid_until         timestamp    not null,
    created_at          timestamptz  not null,
    updated_at          timestamptz  not null
);

create table issue_round (
    id             bigint generated by default as identity primary key,
    policy_id      bigint      not null references coupon_policy (id),
    opened_at      timestamp   not null,
    closed_at      timestamp   not null,
    total_quantity integer     not null,
    created_at     timestamptz not null,
    updated_at     timestamptz not null
);

create index idx_issue_round_policy_id on issue_round (policy_id);

-- (round_id, users_id) Unique 를 일부러 걸지 않았다.
-- 락 없는 1단계에서 동시 요청 시 중복 발급·초과 발급이 실제로 일어나는지 정합성 테스트로 드러내기 위해서다.
create table issued_coupon (
    id         bigint generated by default as identity primary key,
    round_id   bigint      not null references issue_round (id),
    users_id   bigint      not null references users (id),
    status     varchar(20) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

create index idx_issued_coupon_round_users on issued_coupon (round_id, users_id);
create index idx_issued_coupon_users_id on issued_coupon (users_id);
